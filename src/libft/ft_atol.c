#include "push_swap.h"

long	ft_atol(const char *str)
{
	int		i;
	int		sinal;
	long	resultado;

	i = 0;
	sinal = 1;
	resultado = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == ' ')
		i++;
	if (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
			sinal = -1;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		resultado = (resultado * 10) + (str[i] - '0');
		i++;
	}
	return (resultado * sinal);
}
